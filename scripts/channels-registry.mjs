#!/usr/bin/env node
/**
 * Generate src/lib/channels/registry.generated.ts from the folders under channels/.
 *
 * ── Why generated, and why static imports ────────────────────────────────────
 *
 * A channel's bible (cast, voices, series, policy, trend sources) lives in the repo under
 * channels/<slug>/, edited by hand and reviewed like code. The web app runs on Vercel and the
 * pipeline on a Trigger.dev worker; both bundle their code, and a runtime `readFile` of a
 * folder the bundler never saw is a file that exists in git and not in production. Static
 * JSON imports are the one form both bundlers are guaranteed to carry. So the folder listing
 * becomes a module of imports, and this script is what keeps the module and the folders in
 * step.
 *
 * `--check` (wired into `pnpm check` as `check:channels`) fails when the committed module
 * differs from what the folders would generate, or when a folder's characters.json names a
 * different channel than its folder — the mistake `pnpm channel:new` exists to prevent.
 *
 * Usage: node scripts/channels-registry.mjs [--check]
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = 'channels';
const OUT = 'src/lib/channels/registry.generated.ts';
const check = process.argv.includes('--check');

const ident = (s) => s.replace(/[^a-zA-Z0-9]/g, '_');
const problems = [];

const folders = readdirSync(ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const lines = [
  '// GENERATED by scripts/channels-registry.mjs from the folders under channels/. Do not edit:',
  '// run `node scripts/channels-registry.mjs` after adding or removing a channel folder.',
  '// `pnpm check:channels` fails when this file and the folders disagree.',
  '',
];
const entries = [];

for (const slug of folders) {
  const dir = join(ROOT, slug);
  const id = ident(slug);
  for (const f of ['characters.json', 'policy.json']) {
    if (!existsSync(join(dir, f))) problems.push(`${dir}/${f} is missing`);
  }
  try {
    const chars = JSON.parse(readFileSync(join(dir, 'characters.json'), 'utf8'));
    if (chars.channel !== slug) problems.push(`${dir}/characters.json says "channel": "${chars.channel}", not "${slug}"`);
  } catch (err) {
    problems.push(`${dir}/characters.json: ${err.message}`);
  }
  const seriesFiles = existsSync(join(dir, 'series'))
    ? readdirSync(join(dir, 'series')).filter((f) => f.endsWith('.json')).sort()
    : [];
  if (seriesFiles.length === 0) problems.push(`${dir}/series/ holds no series file`);
  const hasTrends = existsSync(join(dir, 'trends.json'));

  lines.push(`import ${id}__characters from '../../../channels/${slug}/characters.json';`);
  lines.push(`import ${id}__policy from '../../../channels/${slug}/policy.json';`);
  if (hasTrends) lines.push(`import ${id}__trends from '../../../channels/${slug}/trends.json';`);
  const seriesIds = [];
  for (const f of seriesFiles) {
    const sid = `${id}__series_${ident(f.replace(/\.json$/, ''))}`;
    lines.push(`import ${sid} from '../../../channels/${slug}/series/${f}';`);
    seriesIds.push(sid);
  }
  entries.push(
    `  '${slug}': { characters: ${id}__characters, policy: ${id}__policy, trends: ${hasTrends ? `${id}__trends` : 'null'}, series: [${seriesIds.join(', ')}] },`,
  );
}

lines.push('');
lines.push('export const CHANNEL_FOLDERS: Readonly<Record<string, { characters: unknown; policy: unknown; trends: unknown; series: readonly unknown[] }>> = {');
lines.push(...entries);
lines.push('};');
lines.push('');
const out = lines.join('\n');

if (problems.length) {
  console.error('FAIL: channel folders are malformed:');
  for (const p of problems) console.error(`  ${p}`);
  process.exit(1);
}

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error(`FAIL: ${OUT} is out of date with channels/. Run: node scripts/channels-registry.mjs`);
    process.exit(1);
  }
  console.log(`PASS: ${folders.length} channel folder(s) registered: ${folders.join(', ')}`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${folders.length} folder(s): ${folders.join(', ')})`);
}
